    STATUS_BAR_HEIGHT = 32
    INPUT_MAX_HEIGHT = 150
    CHAT_MAX_WIDTH = 820
    TOP_BAR_HEIGHT = 52
    ICON_SM = 16
    ICON_MD = 20
    ICON_LG = 24
